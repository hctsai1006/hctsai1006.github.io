// wrapping
// ---------------------------------------------------------------------------

const isSpace = (cluster: string): boolean => cluster === ' ' || cluster === '\t';

/**
 * Break one line to `width`, the way `Format-Table -Wrap` and Format-List do.
 *
 * The rule looks like ordinary word wrap and is not, which four measurements
 * pin down:
 *
 *   'alpha beta gamma delta' at 10  ->  alpha / beta / gamma / delta
 *   'alpha beta gamma delta' at 11  ->  alpha beta / gamma delta
 *   'ab cdefghijk lm'        at  7  ->  ab cdef / ghijk / lm
 *   'supercalifragilistic and short' at 10 -> supercalif / ragilistic / " and short"
 *
 * Line one says the break must leave room for the space as well as the words,
 * so the limit is `width - 1` and `alpha beta` — exactly ten columns — does not
 * fit in ten. Line three says the wrap gives up when the NEXT word could not fit
 * on a line of its own and cuts at the width instead. Line four says the
 * remainder is emitted verbatim once it fits, leading space and all.
 *
 * The chunk KEEPS the whitespace it broke at. Format-List shows that space;
 * Format-Table's wrapping writer trims it away. Same algorithm, different
 * writer, and that is why `alpha ` and `alpha` are both correct answers.
 */
export function wrapText(text: string, width: number): string[] {
  if (width <= 0) return [text];
  const cells = clusters(text).map((cluster) => ({ cluster, width: graphemeWidth(cluster) }));

  const out: string[] = [];
  let start = 0;

  const widthFrom = (from: number, to: number): number => {
    let total = 0;
    for (let i = from; i < to; i++) total += cells[i]?.width ?? 0;
    return total;
  };

  while (widthFrom(start, cells.length) > width) {
    // The last whitespace whose chunk — including that whitespace — fits.
    let breakAt = -1;
    let used = 0;
    for (let i = start; i < cells.length; i++) {
      const cell = cells[i];
      if (cell === undefined) break;
      used += cell.width;
      if (used > width) break;
      if (isSpace(cell.cluster)) breakAt = i;
    }

    if (breakAt !== -1) {
      // Would the next word fit on a line by itself? If not, the wrap cannot
      // help and pwsh cuts at the width instead.
      let wordEnd = breakAt + 1;
      while (wordEnd < cells.length && !isSpace(cells[wordEnd]?.cluster ?? ' ')) wordEnd += 1;
      if (widthFrom(breakAt + 1, wordEnd) > width) breakAt = -1;
    }

    if (breakAt !== -1) {
      out.push(cells.slice(start, breakAt + 1).map((c) => c.cluster).join(''));
      start = breakAt + 1;
      continue;
    }

    let taken = 0;
    let end = start;
    while (end < cells.length && taken + (cells[end]?.width ?? 0) <= width) {
      taken += cells[end]?.width ?? 0;
      end += 1;
    }
    if (end === start) end = start + 1; // a single cluster wider than the column
    out.push(cells.slice(start, end).map((c) => c.cluster).join(''));
    start = end;
  }

  out.push(cells.slice(start).map((c) => c.cluster).join(''));
  return out;
}

/** Split on newlines first, then wrap each piece. Both views need this order. */
export function wrapLines(text: string, width: number): string[] {
  return text.split(/\r\n|\r|\n/).flatMap((line) => wrapText(line, width));
}

/** Right-trim, which is what the wrapping writer does and the single-line one does not. */
export const trimEnd = (line: string): string => line.replace(/[ \t]+$/, '');
